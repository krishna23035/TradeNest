import { Download } from "lucide-react";
import type { Analysis } from "@/hooks/useStock";

const escapeHtml = (value: string) => value.replace(/[&<>"']/g, (character) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
}[character] ?? character));

export function ReportButton({ analysis, symbol }: { analysis: Analysis; symbol: string }) {
  function download() {
    const { decision, prediction, last, vol, sentiment } = analysis;
    const safeSymbol = escapeHtml(symbol);
    const html = `<!doctype html><html><head><meta charset="utf-8"><title>TradeNest Pro Report — ${safeSymbol}</title>
    <style>
      body{font-family:Inter,system-ui,sans-serif;max-width:760px;margin:40px auto;padding:0 24px;color:#0b1220}
      h1{font-family:'Space Grotesk',sans-serif;margin:0 0 4px}
      .muted{color:#5b6577;font-size:12px}
      .grid{display:grid;grid-template-columns:1fr 1fr 1fr;gap:12px;margin:24px 0}
      .card{border:1px solid #e3e7ef;border-radius:10px;padding:14px}
      .label{font-size:10px;text-transform:uppercase;letter-spacing:.08em;color:#5b6577}
      .val{font-family:'JetBrains Mono',monospace;font-size:18px;font-weight:600;margin-top:4px}
      .badge{display:inline-block;padding:2px 8px;border-radius:6px;font-size:11px;font-weight:600}
      .buy{background:#d1fae5;color:#065f46}.sell{background:#fee2e2;color:#991b1b}.hold{background:#fef3c7;color:#92400e}
      ul{margin:8px 0;padding-left:18px}.disc{margin-top:32px;padding:12px;background:#fff7ed;border-left:3px solid #f59e0b;font-size:12px}
    </style></head><body>
      <h1>TradeNest Pro — ${safeSymbol}</h1>
      <div class="muted">Generated ${new Date().toLocaleString()} · Heuristic decision support · ${analysis.isLive ? "Yahoo historical data" : "deterministic demo data"}</div>
      <div class="grid">
        <div class="card"><div class="label">Action</div><div class="val"><span class="badge ${decision.action.toLowerCase()}">${decision.action}</span></div><div class="muted">Rule score ${decision.signalScore}/100 (not a probability) · Risk ${decision.risk}</div></div>
        <div class="card"><div class="label">Last price</div><div class="val">${last.close.toFixed(2)}</div><div class="muted">20-day vol ${vol}%</div></div>
        <div class="card"><div class="label">Heuristic next</div><div class="val">${prediction.next.toFixed(2)}</div><div class="muted">${prediction.change >= 0 ? "+" : ""}${prediction.change}%</div></div>
      </div>
      <h3>Sentiment: ${sentiment.label}</h3>
      <p>Verified news sentiment was not included in this market report. See the News page for current fetched headlines.</p>
      <h3>Decision rationale</h3>
      <ul>${decision.reasons.map((reason) => `<li>${escapeHtml(reason)}</li>`).join("")}</ul>
      <div class="disc"><strong>Disclaimer:</strong> This report is generated by an automated decision support system for educational purposes only. It is not investment advice. Securities markets are subject to risk; please read all related documents and consult a SEBI-registered investment advisor before investing.</div>
    </body></html>`;
    const blob = new Blob([html], { type: "text/html" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `TradeNestPro_${symbol}_${Date.now()}.html`;
    a.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 60000);
  }
  return (
    <button onClick={download}
      className="inline-flex h-9 items-center gap-2 rounded-md border border-border bg-secondary/60 px-3 text-xs font-medium text-foreground transition hover:border-primary/60 hover:text-primary">
      <Download className="h-3.5 w-3.5" /> Report
    </button>
  );
}
